// Generates src/app/eva-icons.subset.ts: only the Eva icons the app uses.
//
// NbEvaIconsModule registers the whole pack (eva.min.js, 237 KB raw / 52 KB
// gzipped, ~490 icons) while the templates use a few dozen. This script
// scans the source for icon names, copies those SVGs from node_modules and
// writes them as a map the app registers instead of the module.
//
//   node scripts/gen-eva-subset.mjs          # (re)generate the subset
//   node scripts/gen-eva-subset.mjs --check  # fail when the subset is stale
//
// An icon name only exists in the subset when it appears as a quoted string
// somewhere under src/ (`icon="..."` in a template, `icon: '...'` in TS).
// A name built at runtime (`${kind}-outline`) is invisible to this scan, so
// the script prints every template literal that ends in -outline` as a
// warning: add such names to ALWAYS below.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const evaDir = join(root, 'node_modules', 'eva-icons');
const outFile = join(root, 'src', 'app', 'eva-icons.subset.ts');

// Icons Nebular's own components render (select, accordion, datepicker,
// toastr, pagination, chat, search...), which never appear in our templates.
const ALWAYS = [
  'chevron-down-outline', 'chevron-up-outline', 'chevron-left-outline', 'chevron-right-outline',
  'close-outline', 'checkmark-outline', 'alert-triangle-outline',
  'alert-circle-outline', 'question-mark-outline', 'search-outline', 'minus-outline',
  'expand-outline', 'collapse-outline', 'email-outline',
  'paper-plane-outline', 'flash-outline', 'file-text-outline', 'info-outline',
];

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|html)$/.test(name) && !name.endsWith('eva-icons.subset.ts')) out.push(p);
  }
  return out;
}

const available = new Map();
for (const [sub, suffix] of [['outline', ''], ['fill', '']]) {
  for (const f of readdirSync(join(evaDir, sub, 'svg'))) {
    if (f.endsWith('.svg')) available.set(f.slice(0, -4) + suffix, join(evaDir, sub, 'svg', f));
  }
}

const source = walk(join(root, 'src')).map((p) => readFileSync(p, 'utf8')).join('\n');
const used = new Set(ALWAYS);
for (const name of available.keys()) {
  if (source.includes(`'${name}'`) || source.includes(`"${name}"`) || source.includes('`' + name + '`')) used.add(name);
}
const dynamic = source.match(/`[^`\n]*\$\{[^`\n]*\}[^`\n]*-outline`/g) || [];
for (const d of dynamic) console.warn(`warning: runtime icon name ${d} — add its possible values to ALWAYS in scripts/gen-eva-subset.mjs`);

const missing = [...used].filter((n) => !available.has(n));
if (missing.length) {
  console.error('icons not in eva-icons: ' + missing.join(', '));
  process.exit(1);
}

const entries = [...used].sort().map((name) => {
  const svg = readFileSync(available.get(name), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  return `  '${name}': '${inner.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`;
});

const body = `// GENERATED by scripts/gen-eva-subset.mjs — do not edit; run the script
// after using a new icon name. ${entries.length} icons.
export const EVA_ICON_SUBSET: Record<string, string> = {
${entries.join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== body) {
    console.error('src/app/eva-icons.subset.ts is stale: run `node scripts/gen-eva-subset.mjs`');
    process.exit(1);
  }
  console.log(`eva subset up to date (${entries.length} icons)`);
} else {
  writeFileSync(outFile, body);
  console.log(`wrote ${outFile} (${entries.length} icons)`);
}
